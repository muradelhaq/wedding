window.detectWeddingLanguage = function() {
    // 1. Check LocalStorage
    try {
        const saved = localStorage.getItem('wedding_lang');
        if (saved && ['id', 'tr', 'en'].includes(saved)) {
            return saved;
        }
    } catch(e) {}

    // 2. Check URL search param (?lang=tr or ?lang=en or ?lang=id)
    try {
        const urlParams = new URLSearchParams(window.location.search);
        const urlLang = urlParams.get('lang');
        if (urlLang && ['id', 'tr', 'en'].includes(urlLang.toLowerCase())) {
            return urlLang.toLowerCase();
        }
    } catch(e) {}

    // 3. Check Browser / Device Language
    try {
        const browserLang = (navigator.language || navigator.userLanguage || 'id').toLowerCase();
        if (browserLang.startsWith('tr')) {
            return 'tr';
        }
        if (browserLang.startsWith('id') || browserLang.startsWith('ms')) {
            return 'id';
        }
        if (browserLang.startsWith('en')) {
            return 'en';
        }
    } catch(e) {}

    // 4. Default fallback
    return 'id';
};
